# Normalise metadata values without converting uncertain or mixed values into
# known sexes/stages. DEFRA rules only distinguish exact values below.
normalise_sex_stage <- function(x) {
  x <- normalise_name(x)
  x[x %in% c("na", "n/a", "unknown", "uncertain", "")] <- ""
  x
}

features_with_threat <- features_df %>%
  left_join(row_mapping, by = "Species_Key", suffix = c("", ".mapping")) %>%
  mutate(
    Genus_Key = str_to_lower(Genus),
    Epithet_Key = str_to_lower(Specific_Epithet),
    Scientific_Name_Key = normalise_name(Scientific_Name),
    Is_Conditional_Taxon = Genus_Key %in% str_to_lower(conditional_genera),
        Sex_Key = normalise_sex_stage(sex),
    Stage_Key = normalise_sex_stage(stage),

    # Recording-level rules transcribed from the 2012 Appendix 12 mammal list:
    # adult males are Category 1; females and young are Category 2.
    # These are used only when the species-level map has intentionally left
    # the conditional taxon unresolved and the recorded sex/stage is clear.
        Conditional_Category = case_when(
      # Do not override an existing species-level category.
      !is.na(DEFRA_Category) ~ NA_integer_,

      # Western and Eastern Roe Deer:
      # Require an unambiguous sex/stage combination.
      Genus_Key == "capreolus" &
        Stage_Key %in% c("juvenile", "young") ~ 2L,

      Genus_Key == "capreolus" &
        Sex_Key == "female" &
        Stage_Key == "adult" ~ 2L,

      Genus_Key == "capreolus" &
        Sex_Key == "male" &
        Stage_Key == "adult" ~ 1L,

      # Caribou / reindeer.
      Genus_Key == "rangifer" &
        Stage_Key %in% c("juvenile", "young") ~ 2L,

      Genus_Key == "rangifer" &
        Sex_Key == "female" &
        Stage_Key == "adult" ~ 2L,

      Genus_Key == "rangifer" &
        Sex_Key == "male" &
        Stage_Key == "adult" ~ 1L,

      # Tragelaphus species.
      Genus_Key == "tragelaphus" &
        Stage_Key %in% c("juvenile", "young") ~ 2L,

      Genus_Key == "tragelaphus" &
        Sex_Key == "female" &
        Stage_Key == "adult" ~ 2L,

      Genus_Key == "tragelaphus" &
        Sex_Key == "male" &
        Stage_Key == "adult" ~ 1L,

      # Cervus species not already covered by explicit Category 1 rules.
      Genus_Key == "cervus" &
        !Scientific_Name_Key %in% cat1_species &
        Stage_Key %in% c("juvenile", "young") ~ 2L,

      Genus_Key == "cervus" &
        !Scientific_Name_Key %in% cat1_species &
        Sex_Key == "female" &
        Stage_Key == "adult" ~ 2L,

      Genus_Key == "cervus" &
        !Scientific_Name_Key %in% cat1_species &
        Sex_Key == "male" &
        Stage_Key == "adult" ~ 1L,

      # Fallow Deer.
      Genus_Key == "dama" &
        str_detect(Species_Key, "fallow deer") &
        Stage_Key %in% c("juvenile", "young") ~ 2L,

      Genus_Key == "dama" &
        str_detect(Species_Key, "fallow deer") &
        Sex_Key == "female" &
        Stage_Key == "adult" ~ 2L,

      Genus_Key == "dama" &
        str_detect(Species_Key, "fallow deer") &
        Sex_Key == "male" &
        Stage_Key == "adult" ~ 1L,

      # Unresolved or ambiguous cases stay Unknown.
      TRUE ~ NA_integer_
    ),

    DEFRA_Category = coalesce(DEFRA_Category, Conditional_Category),
    DEFRA_Category_Name = case_when(
      DEFRA_Category == 1L ~ "Category 1 - Greater Risk",
      DEFRA_Category == 2L ~ "Category 2 - Less Risk",
      DEFRA_Category == 3L ~ "Category 3 - Least Risk",
      TRUE ~ "Unknown / unresolved"
    ),
    Threat_Level = case_when(
      DEFRA_Category == 1L ~ "Dangerous",
      DEFRA_Category == 2L ~ "Weak",
      DEFRA_Category == 3L ~ "Normal",
      TRUE ~ "Unknown"
    ),
    Match_Level = case_when(
      !is.na(Conditional_Category) ~ "Recording-level DEFRA 2012 sex/age condition matched",
      is.na(DEFRA_Category) & Is_Conditional_Taxon ~ "Unresolved: conditional Appendix 12 rule and recording metadata insufficient",
      is.na(DEFRA_Category) ~ "Needs review: no explicit verified category in local mapping",
      TRUE ~ Match_Level
    ),
    Appendix_Reference = case_when(
      !is.na(Conditional_Category) ~ "DEFRA (2012), Secretary of State's Standards of Modern Zoo Practice, Appendix 12, mammal listings (printed pp. 74-76; Roe Deer and related conditional entries)",
      is.na(DEFRA_Category) & !is.na(Scientific_Name) ~ "DEFRA (2012), Appendix 12; exact listing or modern taxonomy crosswalk still needs review",
      TRUE ~ Appendix_Reference
    ),
    Caveat_Notes = case_when(
      !is.na(Conditional_Category) ~ "Category assigned at recording level from the 2012 Appendix 12 subgroup/sex-age entry; this remains a zoo-visitor hazard category, not a measure of danger from the animal's call or in the wild.",
      is.na(DEFRA_Category) & Is_Conditional_Taxon ~ "The 2012 listing has a conditional or subgroup-specific entry. Sex/stage is uncertain, mixed, missing, or insufficient to choose a category; retained as Unknown.",
      is.na(DEFRA_Category) ~ "The current local mapping has not verified an exact Appendix 12 entry for this taxon. Retained as Unknown instead of assuming Category 3.",
      TRUE ~ Caveat_Notes
    ),
    Audit_Status = case_when(
      !is.na(Conditional_Category) ~ "Conditional category assigned at recording level; verify scientific-name crosswalk before final model use",
      is.na(DEFRA_Category) & Is_Conditional_Taxon ~ "Needs review: conditional category unresolved at recording level",
      is.na(DEFRA_Category) ~ "Needs review: exact Appendix 12 match not verified",
      TRUE ~ Audit_Status
    )
  ) %>%
  select(-Species_Key, -Genus_Key, -Epithet_Key, -Scientific_Name_Key,
         -Sex_Key, -Stage_Key, -Conditional_Category)

