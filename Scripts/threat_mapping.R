# --------------------------- 1. Helper functions ---------------------

first_existing <- function(paths) {
  found <- paths[file.exists(paths)]
  if (length(found) == 0) return(NA_character_)
  found[[1]]
}

normalise_name <- function(x) {
  x <- as.character(x)
  x <- str_replace_all(x, "[’‘`´]", "'")
  x <- str_replace_all(x, "[–—]", "-")
  x <- str_squish(str_to_lower(x))
  x[is.na(x)] <- ""
  x
}

is_blank <- function(x) {
  is.na(x) | str_squish(as.character(x)) == ""
}

# --------------------------- 2. Locate files -------------------------

feature_path <- first_existing(c(
  "Data_Processed/final_ml_features_with_species.csv",
  "final_ml_features_with_species.csv",
  "Data_Processed/final_ml_features_with_species_2.csv",
