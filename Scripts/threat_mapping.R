metadata_path <- first_existing(c(
  "Data_Processed/combined_land_mammals.csv",
  "combined_land_mammals.csv"
))

if (is.na(feature_path)) {
  stop("Could not find final_ml_features_with_species.csv. Run the script from the project root or put the file in Data_Processed/.")
}
if (is.na(metadata_path)) {
  stop("Could not find combined_land_mammals.csv. Run the script from the project root or put the file in Data_Processed/.")
}

output_dir <- if (dir.exists("Data_Processed")) "Data_Processed" else "."
dir.create(output_dir, showWarnings = FALSE, recursive = TRUE)

# --------------------------- 3. Read data ----------------------------

features_df <- read_csv(feature_path, show_col_types = FALSE)
metadata_df <- read_csv(
  metadata_path,
  col_types = cols(date = col_character()),
  show_col_types = FALSE
)

if (!("Species" %in% names(features_df))) {
      stop("The feature dataset must contain a column named 'Species'.")
}
if (!("File_Name" %in% names(features_df))) {
  stop("The feature dataset must contain a File_Name column such as XC1158149.mp3.")
}

required_metadata_columns <- c("id", "en", "gen", "sp", "sex", "stage")
if (!all(required_metadata_columns %in% names(metadata_df))) {
  stop("combined_land_mammals.csv must contain id, en, gen, sp, sex, and stage columns.")
}

# Drop labels generated by earlier runs and refresh sex/stage from the source
# metadata by recording ID. This avoids stale metadata and prevents row drift.
generated_columns <- c(
  "Recording_ID", "Species_Key", "Genus", "Specific_Epithet",
  "Scientific_Name", "DEFRA_Category", "DEFRA_Category_Name",
  "Threat_Level", "Match_Level", "Appendix_Reference", "Caveat_Notes",
  "Audit_Status", "sex", "stage", "Conditional_Category"
)
features_df <- features_df %>%
  select(-any_of(generated_columns)) %>%
  mutate(
    Species = as.character(Species),
    Recording_ID = str_extract(as.character(File_Name), "(?<=XC)\\d+"),
    Species_Key = normalise_name(Species)
  )

if (any(is_blank(features_df$Recording_ID))) {
  stop("Could not extract one or more recording IDs from File_Name. Expected names like XC1158149.mp3.")
}
if (anyDuplicated(features_df$Recording_ID) > 0) {
  stop("Duplicate recording IDs found in the feature dataset. Resolve duplicates before mapping.")
}

metadata_identity <- metadata_df %>%
  transmute(
    Recording_ID = as.character(id),
    en = as.character(en),
    gen = as.character(gen),
    sp = as.character(sp),
    sex = as.character(sex),
    stage = as.character(stage)
  ) %>%
  distinct() %>%
  filter(!is_blank(Recording_ID))

metadata_id_conflicts <- metadata_identity %>%
  count(Recording_ID, name = "Metadata_Rows") %>%
  filter(Metadata_Rows > 1)
if (nrow(metadata_id_conflicts) > 0) {
  write_csv(metadata_id_conflicts,
            file.path(output_dir, "defra_2012_recording_metadata_conflicts.csv"),
            na = "")
  stop("Some recording IDs map to multiple metadata records. See defra_2012_recording_metadata_conflicts.csv.")
}

recording_metadata <- metadata_identity %>%
  select(Recording_ID, sex, stage)

input_row_count <- nrow(features_df)
features_df <- features_df %>%
  left_join(recording_metadata, by = "Recording_ID")
if (nrow(features_df) != input_row_count) {
  stop("The recording metadata join changed the number of feature rows.")
}

unmatched_recording_ids <- features_df %>%
  filter(is.na(sex) & is.na(stage)) %>%
  distinct(Recording_ID)
write_csv(
  unmatched_recording_ids,
  file.path(output_dir, "defra_2012_recordings_missing_sex_stage.csv"),
  na = ""
)

# --------------------------- 4. Build taxonomy lookup ---------------

# Species in the audio feature file are English/common names. The
# combined metadata provides their scientific genus and epithet.
meta_tax <- metadata_df %>%
  transmute(
    Species_Key = normalise_name(en),
    Genus = str_to_title(str_squish(as.character(gen))),
    Specific_Epithet = str_to_lower(str_squish(as.character(sp)))
  ) %>%
  filter(
    Species_Key != "",
    !is_blank(Genus),
    !is_blank(Specific_Epithet)
  ) %>%
  mutate(
    Scientific_Name = paste(Genus, Specific_Epithet),
    Scientific_Name_Key = normalise_name(Scientific_Name)
  ) %>%
  distinct(Species_Key, Genus, Specific_Epithet,
           Scientific_Name, Scientific_Name_Key)

# If one English name maps to multiple binomials, do not choose one
# arbitrarily. Save the conflict and leave those records Unknown.
taxonomy_conflicts <- meta_tax %>%
  group_by(Species_Key) %>%
  summarise(
    Number_Of_Taxa = n_distinct(Scientific_Name_Key),
    Scientific_Name_Options = paste(sort(unique(Scientific_Name)), collapse = " | "),
    .groups = "drop"
  ) %>%
  filter(Number_Of_Taxa > 1)

write_csv(
  taxonomy_conflicts,
  file.path(output_dir, "defra_2012_taxonomy_conflicts.csv"),
  na = ""
)

tax_lookup <- meta_tax %>%
  anti_join(taxonomy_conflicts %>% select(Species_Key), by = "Species_Key") %>%
  distinct(Species_Key, .keep_all = TRUE)

species_summary <- features_df %>%
  filter(Species_Key != "") %>%
  count(Species_Key, name = "Recording_Count") %>%
  left_join(
    features_df %>% filter(Species_Key != "") %>%
      distinct(Species_Key, Species) %>%
      group_by(Species_Key) %>% slice(1) %>% ungroup(),
    by = "Species_Key"
  ) %>%
  left_join(tax_lookup, by = "Species_Key") %>%
  arrange(desc(Recording_Count))

