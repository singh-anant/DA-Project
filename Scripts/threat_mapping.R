# --------------------------- 6. Assign reference categories ---------

species_audit <- species_summary %>%
  mutate(
    Genus_Key = str_to_lower(Genus),
    Scientific_Name_Key = normalise_name(Scientific_Name),
    Is_Special_Record = Species_Key %in% special_non_taxa,
    Has_Taxonomy = !is_blank(Genus) & !is_blank(Specific_Epithet) &
      !is_blank(Scientific_Name),
    Is_Conditional_Taxon = Genus_Key %in% str_to_lower(conditional_genera),
    Needs_Taxonomy_Review = Genus_Key %in% str_to_lower(review_genera),

    DEFRA_Category = case_when(
      # Records without a valid animal identity never receive a DEFRA label.
      Is_Special_Record ~ NA_integer_,
      !Has_Taxonomy ~ NA_integer_,

      # Domestic-dog exceptions must precede the C. lupus rule because some
            # metadata taxonomies record domestic dogs under Canis lupus.
      Genus_Key == "canis" & Species_Key %in% c("dog", "domestic dog") ~ 3L,
      Genus_Key == "canis" & str_to_lower(Specific_Epithet) == "familiaris" ~ 3L,

      # Explicit species-level entries and special cases.
      Scientific_Name_Key %in% cat1_species ~ 1L,
      Scientific_Name_Key %in% cat2_species ~ 2L,
      Scientific_Name_Key == "felis catus" ~ 3L,

      # Canidae: Appendix lists Canis lupus as Category 1 and other wild
      # Canis species such as coyotes/jackals as Category 2. The domestic-dog
      # exceptions above are handled before the C. lupus rule.
      Genus_Key == "canis" & str_to_lower(Specific_Epithet) == "lupus" ~ 1L,
      Genus_Key == "canis" ~ 2L,

      # Felis wild species/wild cats and lynxes are Category 1; the domestic
      # cat exception above is Category 3 under the Appendix 12 rule.
      Genus_Key %in% str_to_lower(c("Felis", "Panthera", "Neofelis", "Acinonyx",
                                    "Lynx", "Leopardus", "Caracal", "Prionailurus",
                                    "Herpailurus")) ~ 1L,

      # Wild horses, asses and zebras are listed Category 1; domestic horse
      # and ass are not covered by that wild-species entry.
      Genus_Key == "equus" & Species_Key %in% c(
        "horse", "domestic horse", "donkey", "domestic donkey", "ass", "domestic ass"
      ) ~ 3L,
      Genus_Key == "equus" & str_detect(
        Species_Key, "wild horse|wild ass|przewalski|zebra|onager|kiang|kulan|tarpan"
      ) ~ 1L,
      # Other Equus records require a check against the 2012 wild-species entry;
      # do not assume an ambiguous common name means a wild animal.
      Genus_Key == "equus" ~ NA_integer_,

      # DEFRA listed wild Sus species (wild boar) at Category 1; normal
      # domestic pigs are not part of that entry.
      Genus_Key == "sus" & Species_Key %in% c(
        "pig", "domestic pig", "swine", "domestic swine"
      ) ~ 3L,
      Genus_Key == "sus" & str_detect(Species_Key, "wild boar|wild pig") ~ 1L,
      Genus_Key == "sus" ~ NA_integer_,

      # The Appendix distinguishes specified Bos taxa at Category 1 from
      # other species in the listed group at Category 2.
      Genus_Key == "bos" & str_detect(Species_Key, "bison|gaur|banteng|yak|kouprey|ankole") ~ 1L,
      Genus_Key == "bos" ~ 2L,

      # Exact exceptions for the conditional sheep/goat categories.
      Genus_Key == "capra" & (
        str_detect(Species_Key, "domestic goat") |
          (Species_Key == "goat" & str_to_lower(Specific_Epithet) == "hircus")
      ) ~ 3L,
      Genus_Key == "ovis" & str_detect(Species_Key, "argali|bighorn") ~ 1L,
      Genus_Key == "ovis" & str_detect(Species_Key, "mouflon|urial") ~ 2L,
      Genus_Key == "ovis" & str_detect(Species_Key, "domestic sheep") ~ 3L,

      # The Appendix has explicit male/female/young or size-group caveats
      # for these genera. Species-only data cannot determine these reliably.
      Is_Conditional_Taxon ~ NA_integer_,
      Needs_Taxonomy_Review ~ NA_integer_,

      # Category 1 genus/group listings. The explicit special cases above
      # are evaluated first, so category-dependent taxa are not overridden.
      Genus_Key %in% str_to_lower(cat1_genera) ~ 1L,

      # Category 2 genus/group listings.
      Genus_Key %in% str_to_lower(cat2_genera) ~ 2L,

      # An unlisted taxon can only be Category 3 under Rule 3.1 after the
      # entire Appendix 12 list has been checked, not merely because this
      # script lacks a Category 1/2 rule for it.
      Scientific_Name_Key %in% reviewed_category3_species ~ 3L,
      TRUE ~ NA_integer_
    ),

    DEFRA_Category_Name = case_when(
      DEFRA_Category == 1L ~ "Category 1 - Greater Risk",
      DEFRA_Category == 2L ~ "Category 2 - Less Risk",
      DEFRA_Category == 3L ~ "Category 3 - Least Risk",
      TRUE ~ "Unknown / unresolved"
    ),

    Threat_Level = case_when(
      DEFRA_Category == 1L ~ "Dangerous",
      DEFRA_Category == 2L ~ "Weak",
      DEFRA_Category == 3L ~ "Normal",
      TRUE ~ "Unknown"
    ),

    Match_Level = case_when(
      Is_Special_Record ~ "Unmatched: not an identified animal taxon",
      !Has_Taxonomy ~ "Unmatched: missing scientific taxonomy or conflicting metadata",
      Scientific_Name_Key %in% cat1_species & DEFRA_Category == 1L ~ "Exact species-level Category 1 match",
      Scientific_Name_Key %in% cat2_species & DEFRA_Category == 2L ~ "Exact species-level Category 2 match",
      Scientific_Name_Key == "felis catus" ~ "Domestic-cat exception / Rule 3.1",
      Scientific_Name_Key %in% reviewed_category3_species & DEFRA_Category == 3L ~ "Manually verified unlisted taxon / Appendix 12 Rule 3.1",
      Genus_Key %in% str_to_lower(modern_cat1_crosswalk_genera) ~ "Modern-genus crosswalk to listed Category 1 group",
      Genus_Key %in% str_to_lower(modern_cat2_crosswalk_genera) ~ "Modern-genus crosswalk to listed Category 2 group",
      Genus_Key == "canis" & DEFRA_Category == 1L ~ "Exact species-level Category 1 match",
      Genus_Key == "canis" & DEFRA_Category == 2L ~ "Canis wild-species group match",
      Genus_Key == "canis" & DEFRA_Category == 3L ~ "Domestic-dog exception / Rule 3.1",
            Genus_Key == "equus" & DEFRA_Category == 1L ~ "Wild Equus group match",
      Genus_Key == "equus" & DEFRA_Category == 3L ~ "Domestic Equus exception / Rule 3.1",
      Genus_Key == "sus" & DEFRA_Category == 1L ~ "Wild Sus group match",
      Genus_Key == "sus" & DEFRA_Category == 3L ~ "Domestic-pig exception / Rule 3.1",
      Genus_Key == "bos" & DEFRA_Category == 1L ~ "Named Category 1 Bos group match",
      Genus_Key == "bos" & DEFRA_Category == 2L ~ "Other Bos group / Category 2",
      Is_Conditional_Taxon & is.na(DEFRA_Category) ~ "Unresolved: Appendix category depends on sex/age or deer grouping",
      Needs_Taxonomy_Review & is.na(DEFRA_Category) ~ "Unresolved: current genus needs checking against 2012 taxonomy",
      Genus_Key %in% str_to_lower(cat1_genera) ~ "Listed genus/group Category 1 match",
      Genus_Key %in% str_to_lower(cat2_genera) ~ "Listed genus/group Category 2 match",
      DEFRA_Category == 1L ~ "Specific Appendix 12 Category 1 exception/group match",
      DEFRA_Category == 2L ~ "Specific Appendix 12 Category 2 exception/group match",
      DEFRA_Category == 3L ~ "Explicit Category 3 exception / Rule 3.1 application",
      is.na(DEFRA_Category) & Is_Conditional_Taxon ~ "Unresolved: conditional 2012 taxon rule; check recording sex/stage or subgroup",
      is.na(DEFRA_Category) & Needs_Taxonomy_Review ~ "Unresolved: current genus needs checking against 2012 taxonomy",
      is.na(DEFRA_Category) ~ "Needs review: no explicit verified category in local mapping",
      TRUE ~ "Unmatched"
    ),

    Appendix_Reference = case_when(
      DEFRA_Category %in% c(1L, 2L) ~ "DEFRA (2012), Secretary of State's Standards of Modern Zoo Practice, Appendix 12, mammal listings (printed pp. 65-76; PDF pp. 68-79)",
      DEFRA_Category == 3L ~ "DEFRA (2012), Appendix 12, Rule 3.1 (printed p. 63): taxa not listed in Category 1 or 2 are Category 3",
      Is_Conditional_Taxon & is.na(DEFRA_Category) ~ "DEFRA (2012), Appendix 12, mammal listings, printed pp. 65-76; taxon-specific condition needs review",
      Needs_Taxonomy_Review & is.na(DEFRA_Category) ~ "DEFRA (2012), Appendix 12, mammal listings, printed pp. 65-76; modern taxonomy crosswalk needs review",
      is.na(DEFRA_Category) ~ "DEFRA (2012), Appendix 12, mammal listings; exact listing/crosswalk has not yet been verified",
      TRUE ~ ""
    ),

    Caveat_Notes = case_when(
      Is_Special_Record ~ "No verified species-level identity; keep Unknown.",
      !Has_Taxonomy ~ "Scientific name missing or conflicting in combined_land_mammals.csv; review taxonomy.",
      Genus_Key %in% str_to_lower(modern_cat1_crosswalk_genera) ~ "Modern genus crosswalk to an older Appendix 12 group; confirm taxonomic equivalence in the audit.",
      Genus_Key %in% str_to_lower(modern_cat2_crosswalk_genera) ~ "Modern genus crosswalk to an older Appendix 12 group; confirm taxonomic equivalence in the audit.",
      Is_Conditional_Taxon & is.na(DEFRA_Category) ~ "Appendix 12 contains a taxon subgroup or sex/age condition. Apply only after verifying the scientific taxon and relevant recording metadata.",
      Needs_Taxonomy_Review & is.na(DEFRA_Category) ~ "Current genus is not directly reconciled with the 2012 listing; verify taxonomy before assigning a category.",
      Scientific_Name_Key %in% reviewed_category3_species & DEFRA_Category == 3L ~ "Manual review confirmed this scientific taxon is not listed in 2012 Appendix 12 Category 1 or Category 2; Category 3 assigned under Rule 3.1. This is specific to zoo visitors.",
      DEFRA_Category == 3L ~ "Category 3 is the project's label for DEFRA Category 3; it does not mean harmless. DEFRA's rule is specific to zoo visitors.",
      DEFRA_Category == 1L ~ "Project label for DEFRA Category 1 (Greater Risk), which concerns visitors to licensed zoological gardens.",
      DEFRA_Category == 2L ~ "Project label for DEFRA Category 2 (Less Risk), which concerns visitors to licensed zoological gardens.",
      TRUE ~ "Classification unresolved; the local mapping has not verified the exact Appendix 12 listing. Kept Unknown."
    ),

    Audit_Status = case_when(
      !is.na(DEFRA_Category) ~ "Category assigned by explicit local rule; verify against the cited Appendix 12 entry before final model use",
      Is_Conditional_Taxon ~ "Needs review: conditional taxon; category may depend on subgroup or recording sex/stage",
      Needs_Taxonomy_Review ~ "Needs review: modern taxonomy crosswalk",
      TRUE ~ "Needs review: no explicit verified category in local mapping"
    )
  ) %>%
  select(
    Species, Recording_Count, Genus, Specific_Epithet, Scientific_Name,
