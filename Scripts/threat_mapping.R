# =====================================================================
# threat_mapping.R
# Purpose:
#   Add reference-based animal hazard categories from the 2012 DEFRA
#   Secretary of State's Standards of Modern Zoo Practice, Appendix 12.
#
# Input:
#   Data_Processed/final_ml_features_with_species.csv
#   Data_Processed/combined_land_mammals.csv
#
# Outputs:
#   Data_Processed/species_threat_mapping.csv
#   Data_Processed/final_ml_features_with_threat.csv
#   Data_Processed/defra_2012_taxonomy_conflicts.csv
#   Data_Processed/defra_2012_species_needing_review.csv
#   Data_Processed/defra_2012_recordings_needing_review.csv
#
# Project-specific label mapping (not DEFRA's original wording):
#   DEFRA Category 1 (Greater Risk) -> Dangerous
#   DEFRA Category 2 (Less Risk)    -> Weak
#   DEFRA Category 3 (Least Risk)   -> Normal
#   Missing/conflicting/conditional classification -> Unknown
#
# Important:
#   - The DEFRA categories concern hazard to visitors in licensed zoos; they
#     do not measure danger from an animal encountered in the wild, nor can
#     they be inferred from its audio.
#   - Conditional categories are assigned at recording level only when the
#     exact DEFRA condition and recording metadata support the assignment.
#   - The local taxon lists are not assumed complete. A taxon not recognised
#     by the rules is kept Unknown for review rather than defaulted to Category 3.
#   - Category 3 is assigned only by an explicit known exception in this
#     script until the full Appendix 12 crosswalk has been verified.
#   - The existing Target_Label column is preserved, but it is NOT the
#     DEFRA target. Train a DEFRA model using Threat_Level instead.
# =====================================================================

