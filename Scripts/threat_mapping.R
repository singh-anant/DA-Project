# Keep these Unknown rather than silently applying the Category 3 default.
review_genera <- c(
  "Notamacropus", "Osphranter", "Lontra", "Dicotyles"
)

# Common-name records that are not identified animal taxa.
special_non_taxa <- normalise_name(c(
